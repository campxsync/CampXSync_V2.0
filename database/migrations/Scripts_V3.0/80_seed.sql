-- ---- copy templates into a tenant (idempotent; also removes template permissions that were withdrawn)
create or replace function iam.seed_system_roles(p_tenant uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  insert into iam.roles (tenant_id, code, name, description, is_system)
  select p_tenant, t.code, t.name, t.scope_note, true from iam.role_templates t where t.deleted_at is null
  on conflict do nothing;
  insert into iam.role_permissions (tenant_id, role_id, permission_id)
  select p_tenant, r.id, p.id
    from iam.role_template_permissions tp
    join iam.roles r on r.tenant_id = p_tenant and r.code = tp.role_code and r.college_id is null and r.is_system and r.deleted_at is null
    join iam.permissions p on p.code = tp.permission_code and p.deleted_at is null
   where tp.deleted_at is null
  on conflict do nothing;
  delete from iam.role_permissions rp using iam.roles r, iam.permissions p
   where rp.tenant_id = p_tenant and rp.role_id = r.id and r.tenant_id = p_tenant and r.is_system and r.college_id is null and p.id = rp.permission_id
     and not exists (select 1 from iam.role_template_permissions tp where tp.role_code = r.code and tp.permission_code = p.code and tp.deleted_at is null);
end $$;
create or replace function iam.resync_system_roles() returns void language plpgsql security definer set search_path = '' as $$
declare t record; begin for t in select id from core.tenants where deleted_at is null loop perform iam.seed_system_roles(t.id); end loop; end $$;
revoke execute on function iam.resync_system_roles() from public, anon, authenticated;

create or replace function iam.on_tenant_created() returns trigger language plpgsql security definer set search_path = '' as $$
begin perform iam.seed_system_roles(new.id); return new; end $$;
drop trigger if exists trg_seed_roles on core.tenants;
create trigger trg_seed_roles after insert on core.tenants for each row execute function iam.on_tenant_created();

