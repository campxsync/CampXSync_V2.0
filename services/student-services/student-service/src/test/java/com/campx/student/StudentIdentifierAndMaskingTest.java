package com.campx.student;

import com.campx.student.exception.StudentConflictException;
import com.campx.student.model.*;
import com.campx.student.repository.InMemoryGuardianshipRepository;
import com.campx.student.repository.InMemoryPersonRepository;
import com.campx.student.repository.InMemoryStudentRepository;
import com.campx.student.security.UserSecurityContext;
import com.campx.student.service.StudentDomainService;
import org.junit.Before;
import org.junit.Test;

import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

import static org.junit.Assert.*;

/**
 * Tests for Institutional Student Identifiers, Duplicate Detection, Alternate IDs, and Masking.
 * Covers: STM01-US-006, STM01-US-007, STM01-US-008, STM01-US-009, STM01-US-034, STM01-US-035
 */
public class StudentIdentifierAndMaskingTest {

    private StudentDomainService service;
    private UUID tenantId;
    private UUID collegeId;
    private UserSecurityContext staffContext;
    private UserSecurityContext studentContext;
    private UUID studentUserId;
    private StudentProfileResponse student;

    @Before
    public void setUp() {
        InMemoryPersonRepository personRepo = new InMemoryPersonRepository();
        InMemoryStudentRepository studentRepo = new InMemoryStudentRepository(personRepo);
        InMemoryGuardianshipRepository guardianshipRepo = new InMemoryGuardianshipRepository();

        service = new StudentDomainService(studentRepo, personRepo, guardianshipRepo);

        tenantId = UUID.randomUUID();
        collegeId = UUID.randomUUID();
        staffContext = new UserSecurityContext(UUID.randomUUID(), tenantId, collegeId, null, "college_admin", false);

        studentUserId = UUID.randomUUID();
        studentContext = new UserSecurityContext(studentUserId, tenantId, collegeId, null, "student", false);

        EnrollStudentRequest req = new EnrollStudentRequest();
        req.setFirstName("Ravi");
        req.setLastName("Varma");
        req.setPrimaryEmail("ravi.varma@institution.edu");
        req.setCollegeId(collegeId);
        // Leave enrollmentNo null to test auto-generation
        student = service.enrollStudent(staffContext, req);
        service.linkIamAccount(staffContext, student.getId(), studentUserId);
    }

    @Test
    public void testAutoGeneratedStudentNumberFormat() {
        assertNotNull(student.getEnrollmentNo());
        int currentYear = LocalDate.now().getYear();
        assertTrue(student.getEnrollmentNo().startsWith("STU" + currentYear));
    }

    @Test
    public void testIdempotentEnrollmentReplayReturnsIdenticalResponse() {
        String idempotencyKey = "IDEMP-KEY-778899";

        EnrollStudentRequest req = new EnrollStudentRequest();
        req.setFirstName("Kavita");
        req.setLastName("Krishnan");
        req.setPrimaryEmail("kavita.k@institution.edu");
        req.setCollegeId(collegeId);

        StudentProfileResponse resp1 = service.enrollStudent(staffContext, req, idempotencyKey);
        assertNotNull(resp1.getId());

        // Replaying same creation with same Idempotency-Key
        StudentProfileResponse resp2 = service.enrollStudent(staffContext, req, idempotencyKey);
        assertEquals(resp1.getId(), resp2.getId());
        assertEquals(resp1.getEnrollmentNo(), resp2.getEnrollmentNo());
    }

    @Test
    public void testAddAlternateIdentifierAndFieldMaskingForStudents() {
        PersonIdentifierDto idDto = new PersonIdentifierDto();
        idDto.setIdType("NATIONAL_ID");
        idDto.setIdentifierValue("1234-5678-9012");
        idDto.setIssuingAuthority("Govt of India");

        PersonIdentifierDto created = service.addIdentifier(staffContext, student.getId(), idDto);
        assertNotNull(created.getId());
        assertEquals("NATIONAL_ID", created.getIdType());
        assertEquals("1234-5678-9012", created.getIdentifierValue());
        assertEquals("XXXX-XXXX-9012", created.getMaskedValue());

        // When retrieved by Staff, full value is visible
        List<PersonIdentifierDto> staffView = service.getIdentifiers(staffContext, student.getId());
        assertEquals(1, staffView.size());
        assertEquals("1234-5678-9012", staffView.get(0).getIdentifierValue());

        // When retrieved by Student self-service, value is masked!
        List<PersonIdentifierDto> studentView = service.getIdentifiers(studentContext, student.getId());
        assertEquals(1, studentView.size());
        assertEquals("XXXX-XXXX-9012", studentView.get(0).getIdentifierValue());
    }

    @Test(expected = StudentConflictException.class)
    public void testDuplicateAlternateIdentifierRejected() {
        PersonIdentifierDto id1 = new PersonIdentifierDto();
        id1.setIdType("PASSPORT");
        id1.setIdentifierValue("Z998877");
        service.addIdentifier(staffContext, student.getId(), id1);

        PersonIdentifierDto id2 = new PersonIdentifierDto();
        id2.setIdType("PASSPORT");
        id2.setIdentifierValue("Z998877"); // duplicate ID type and value
        service.addIdentifier(staffContext, student.getId(), id2);
    }
}
